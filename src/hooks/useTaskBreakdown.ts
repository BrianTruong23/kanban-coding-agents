'use client';

import { useState, useCallback } from 'react';
import { Task, TaskBreakdownItem, TaskType } from '@/types/task';
import { createClient } from '@/lib/supabase/client';
import { useAuth } from '@/contexts/AuthContext';
import { useMemo } from 'react';

/**
 * Hook for managing task breakdowns and hierarchical task creation
 */
export const useTaskBreakdown = () => {
  const [isProcessing, setIsProcessing] = useState(false);
  const { user } = useAuth();
  const supabase = useMemo(() => createClient(), []);

  /**
   * Generate task ID with proper formatting
   */
  const generateTaskId = useCallback((type: TaskType, index: number): string => {
    const prefix = {
      epic: 'EPIC',
      ticket: 'TASK',
      subtask: 'SUB'
    }[type];

    return `${prefix}-${Date.now()}-${index}`;
  }, []);

  /**
   * Create tasks from a breakdown result
   * This creates the full hierarchy: epics -> tickets -> subtasks
   */
  const createTasksFromBreakdown = useCallback(
    async (
      breakdown: TaskBreakdownItem[],
      addTask: (task: Task) => Promise<void>
    ): Promise<{ created: number; errors: string[] }> => {
      if (!user) {
        throw new Error('You must be logged in to create tasks');
      }

      setIsProcessing(true);
      let created = 0;
      const errors: string[] = [];
      const taskIdMap = new Map<string, string>(); // title -> actual ID

      try {
        // Process epics first, then tickets, then subtasks (breadth-first)
        const processItem = async (
          item: TaskBreakdownItem,
          parentId?: string,
          level: number = 0
        ): Promise<void> => {
          try {
            // Create the task
            const taskId = generateTaskId(item.type, created);
            const now = Date.now();

            // Map dependencies from titles to actual IDs
            const mappedDependencies = (item.dependencies || [])
              .map(depTitle => taskIdMap.get(depTitle))
              .filter(Boolean) as string[];

            const task: Task = {
              id: crypto.randomUUID(),
              taskId,
              title: item.title,
              description: item.description,
              status: 'backlog',
              priority: item.priority,
              tags: item.tags || [],
              taskType: item.type,
              parentTaskId: parentId,
              definitionOfDone: item.definitionOfDone.map((dod, idx) => ({
                id: `dod-${idx}`,
                description: dod,
                completed: false
              })),
              testNotes: item.testNotes,
              riskFlags: item.riskFlags || [],
              dependencies: mappedDependencies,
              estimatedHours: item.estimatedHours,
              autoGenerated: true,
              createdAt: now,
              updatedAt: now
            };

            await addTask(task);
            taskIdMap.set(item.title, task.id);
            created++;

            // Process children
            if (item.children && item.children.length > 0) {
              for (const child of item.children) {
                await processItem(child, task.id, level + 1);
              }
            }
          } catch (error) {
            const errorMsg = `Failed to create ${item.type}: ${item.title}`;
            console.error(errorMsg, error);
            errors.push(errorMsg);
          }
        };

        // Process all epics
        for (const epic of breakdown) {
          await processItem(epic);
        }

        return { created, errors };
      } finally {
        setIsProcessing(false);
      }
    },
    [user, generateTaskId, supabase]
  );

  /**
   * Save a breakdown result to the database for history
   */
  const saveBreakdown = useCallback(
    async (
      sourceType: 'issue' | 'prd' | 'screenshot' | 'text',
      sourceContent: string,
      breakdown: TaskBreakdownItem[],
      metadata?: Record<string, unknown>
    ) => {
      if (!user) return;

      const totalHours = breakdown.reduce((sum, epic) => sum + epic.estimatedHours, 0);

      const { error } = await supabase
        .from('task_breakdowns')
        .insert({
          user_id: user.id,
          source_type: sourceType,
          source_content: sourceContent,
          source_metadata: metadata || {},
          breakdown_result: {
            epics: breakdown,
            summary: `Breakdown containing ${breakdown.length} epic(s)`,
            totalEstimatedHours: totalHours
          },
          tasks_generated: countTasks(breakdown)
        });

      if (error) {
        console.error('Error saving breakdown:', error);
      }
    },
    [user, supabase]
  );

  return {
    isProcessing,
    createTasksFromBreakdown,
    saveBreakdown
  };
};

/**
 * Count total tasks in a breakdown
 */
function countTasks(items: TaskBreakdownItem[]): number {
  return items.reduce((sum, item) => {
    return sum + 1 + (item.children ? countTasks(item.children) : 0);
  }, 0);
}
