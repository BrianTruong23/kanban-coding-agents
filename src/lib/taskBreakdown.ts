import { Task, TaskType, RiskLevel, DefinitionOfDone, TestNotes, RiskFlag } from '@/types/task';
import { generateId } from './utils';

export interface BreakdownInput {
  type: 'issue' | 'prd' | 'text';
  content: string;
  screenshot?: string; // base64 encoded image
}

export interface BreakdownResult {
  epic: Partial<Task>;
  tickets: Partial<Task>[];
  subtasks: Partial<Task>[];
  dependencies: Map<string, string[]>; // taskId -> [dependent taskIds]
}

/**
 * Analyzes input and breaks it down into epics, tickets, and subtasks
 * This is a rule-based implementation. In production, this could use AI/ML
 */
export class TaskBreakdownService {
  /**
   * Parse a GitHub issue, PRD, or plain text into structured tasks
   */
  static async breakdownTask(input: BreakdownInput): Promise<BreakdownResult> {
    const content = input.content.trim();

    // Parse the content to extract key information
    const parsed = this.parseContent(content, input.type);

    // Create the epic
    const epic = this.createEpic(parsed);

    // Break down into tickets
    const tickets = this.createTickets(parsed, epic.id!);

    // Create subtasks for each ticket
    const subtasks: Partial<Task>[] = [];
    tickets.forEach(ticket => {
      const ticketSubtasks = this.createSubtasks(parsed, ticket.id!);
      subtasks.push(...ticketSubtasks);
    });

    // Identify dependencies
    const dependencies = this.identifyDependencies(tickets, subtasks);

    return {
      epic,
      tickets,
      subtasks,
      dependencies,
    };
  }

  /**
   * Parse content to extract structure
   */
  private static parseContent(content: string, type: string) {
    const lines = content.split('\n').map(l => l.trim()).filter(l => l.length > 0);

    // Extract title (usually first line or line after markdown heading)
    let title = lines[0]?.replace(/^#+\s*/, '') || 'Untitled Task';

    // Extract sections
    const sections: Record<string, string[]> = {
      description: [],
      requirements: [],
      acceptance: [],
      testing: [],
      risks: [],
      dependencies: [],
      technical: [],
    };

    let currentSection = 'description';

    lines.slice(1).forEach(line => {
      // Check for section headers
      const lowerLine = line.toLowerCase();
      if (lowerLine.includes('requirement') || lowerLine.includes('user stor')) {
        currentSection = 'requirements';
      } else if (lowerLine.includes('acceptance') || lowerLine.includes('definition of done') || lowerLine.includes('dod')) {
        currentSection = 'acceptance';
      } else if (lowerLine.includes('test') || lowerLine.includes('qa')) {
        currentSection = 'testing';
      } else if (lowerLine.includes('risk') || lowerLine.includes('concern')) {
        currentSection = 'risks';
      } else if (lowerLine.includes('depend') || lowerLine.includes('prerequisite')) {
        currentSection = 'dependencies';
      } else if (lowerLine.includes('technical') || lowerLine.includes('implementation')) {
        currentSection = 'technical';
      } else if (line.match(/^[#-*]/)) {
        // Skip markdown headers and list markers for section detection
        sections[currentSection].push(line.replace(/^[#-*]\s*/, ''));
      } else {
        sections[currentSection].push(line);
      }
    });

    return {
      title,
      sections,
      rawContent: content,
    };
  }

  /**
   * Create epic from parsed content
   */
  private static createEpic(parsed: any): Partial<Task> {
    const epicId = generateId();

    return {
      id: epicId,
      taskId: `EPIC-${Date.now().toString().slice(-6)}`,
      title: parsed.title,
      description: parsed.sections.description.join('\n') || parsed.rawContent.slice(0, 500),
      type: 'epic' as TaskType,
      status: 'backlog',
      priority: this.detectPriority(parsed.rawContent),
      tags: this.extractTags(parsed.rawContent),
      riskFlags: this.extractRisks(parsed.sections.risks),
      definitionOfDone: this.extractDoD(parsed.sections.acceptance),
      createdAt: Date.now(),
      updatedAt: Date.now(),
      autoGenerated: true,
    };
  }

  /**
   * Create tickets from requirements
   */
  private static createTickets(parsed: any, epicId: string): Partial<Task>[] {
    const requirements = parsed.sections.requirements.length > 0
      ? parsed.sections.requirements
      : this.inferRequirements(parsed);

    return requirements.map((req: string, index: number) => {
      const ticketId = generateId();
      return {
        id: ticketId,
        taskId: `TASK-${Date.now().toString().slice(-6)}-${index + 1}`,
        title: this.cleanRequirementText(req),
        description: `Part of: ${parsed.title}\n\n${req}`,
        type: 'ticket' as TaskType,
        parentId: epicId,
        status: 'backlog',
        priority: this.detectPriority(req),
        tags: this.extractTags(req),
        definitionOfDone: {
          criteria: this.generateDoDCriteria(req),
          completedCriteria: [],
        },
        testNotes: this.generateTestNotes(req),
        riskFlags: this.extractRisks([req]),
        estimatedHours: this.estimateHours(req),
        createdAt: Date.now(),
        updatedAt: Date.now(),
        autoGenerated: true,
      };
    });
  }

  /**
   * Create subtasks for a ticket
   */
  private static createSubtasks(parsed: any, ticketId: string): Partial<Task>[] {
    const technicalSteps = parsed.sections.technical.length > 0
      ? parsed.sections.technical
      : this.inferTechnicalSteps();

    return technicalSteps.slice(0, 5).map((step: string, index: number) => {
      const subtaskId = generateId();
      return {
        id: subtaskId,
        taskId: `SUB-${Date.now().toString().slice(-6)}-${index + 1}`,
        title: this.cleanRequirementText(step),
        description: step,
        type: 'subtask' as TaskType,
        parentId: ticketId,
        status: 'backlog',
        priority: 3,
        tags: ['implementation'],
        estimatedHours: 2,
        createdAt: Date.now(),
        updatedAt: Date.now(),
        autoGenerated: true,
      };
    });
  }

  /**
   * Identify task dependencies
   */
  private static identifyDependencies(
    tickets: Partial<Task>[],
    subtasks: Partial<Task>[]
  ): Map<string, string[]> {
    const deps = new Map<string, string[]>();

    // Rule: Database/backend tasks should come before frontend tasks
    const backendTickets = tickets.filter(t =>
      t.tags?.some(tag => tag.toLowerCase().includes('backend') || tag.toLowerCase().includes('api'))
    );
    const frontendTickets = tickets.filter(t =>
      t.tags?.some(tag => tag.toLowerCase().includes('frontend') || tag.toLowerCase().includes('ui'))
    );

    frontendTickets.forEach(frontend => {
      if (frontend.id && backendTickets.length > 0) {
        deps.set(frontend.id, backendTickets.map(b => b.id!).filter(Boolean));
      }
    });

    // Rule: Testing tasks depend on implementation tasks
    const testingTickets = tickets.filter(t =>
      t.tags?.some(tag => tag.toLowerCase().includes('test'))
    );
    const implementationTickets = tickets.filter(t =>
      !t.tags?.some(tag => tag.toLowerCase().includes('test'))
    );

    testingTickets.forEach(test => {
      if (test.id && implementationTickets.length > 0) {
        const existing = deps.get(test.id) || [];
        deps.set(test.id, [...existing, ...implementationTickets.map(i => i.id!).filter(Boolean)]);
      }
    });

    return deps;
  }

  /**
   * Detect priority from text
   */
  private static detectPriority(text: string): 1 | 2 | 3 | 4 | 5 {
    const lowerText = text.toLowerCase();
    if (lowerText.includes('critical') || lowerText.includes('urgent') || lowerText.includes('asap')) {
      return 5;
    }
    if (lowerText.includes('high priority') || lowerText.includes('important')) {
      return 4;
    }
    if (lowerText.includes('low priority') || lowerText.includes('nice to have')) {
      return 2;
    }
    return 3; // medium by default
  }

  /**
   * Extract tags from text
   */
  private static extractTags(text: string): string[] {
    const tags = new Set<string>();
    const lowerText = text.toLowerCase();

    // Technology tags
    if (lowerText.includes('react') || lowerText.includes('ui') || lowerText.includes('frontend')) {
      tags.add('frontend');
    }
    if (lowerText.includes('api') || lowerText.includes('backend') || lowerText.includes('server')) {
      tags.add('backend');
    }
    if (lowerText.includes('database') || lowerText.includes('db') || lowerText.includes('sql')) {
      tags.add('database');
    }
    if (lowerText.includes('test') || lowerText.includes('qa')) {
      tags.add('testing');
    }
    if (lowerText.includes('bug') || lowerText.includes('fix')) {
      tags.add('bug');
    }
    if (lowerText.includes('feature') || lowerText.includes('new')) {
      tags.add('feature');
    }
    if (lowerText.includes('refactor') || lowerText.includes('improve')) {
      tags.add('refactor');
    }
    if (lowerText.includes('security') || lowerText.includes('auth')) {
      tags.add('security');
    }

    return Array.from(tags);
  }

  /**
   * Extract risks from risk section
   */
  private static extractRisks(riskLines: string[]): RiskFlag[] {
    return riskLines.map(risk => {
      const level = this.detectRiskLevel(risk);
      return {
        level,
        description: risk,
        identifiedAt: Date.now(),
      };
    });
  }

  /**
   * Detect risk level
   */
  private static detectRiskLevel(text: string): RiskLevel {
    const lowerText = text.toLowerCase();
    if (lowerText.includes('critical') || lowerText.includes('blocker')) {
      return 'critical';
    }
    if (lowerText.includes('high') || lowerText.includes('major')) {
      return 'high';
    }
    if (lowerText.includes('low') || lowerText.includes('minor')) {
      return 'low';
    }
    return 'medium';
  }

  /**
   * Extract Definition of Done
   */
  private static extractDoD(acceptanceLines: string[]): DefinitionOfDone {
    const criteria = acceptanceLines.length > 0
      ? acceptanceLines
      : [
          'Code is written and tested',
          'Unit tests pass',
          'Code review completed',
          'Documentation updated',
        ];

    return {
      criteria,
      completedCriteria: [],
    };
  }

  /**
   * Generate DoD criteria for a requirement
   */
  private static generateDoDCriteria(requirement: string): string[] {
    const criteria = [
      'Implementation complete',
      'Unit tests written and passing',
      'Integration tests passing',
      'Code reviewed and approved',
    ];

    if (requirement.toLowerCase().includes('ui') || requirement.toLowerCase().includes('frontend')) {
      criteria.push('UI/UX reviewed');
      criteria.push('Responsive design verified');
    }

    if (requirement.toLowerCase().includes('api') || requirement.toLowerCase().includes('backend')) {
      criteria.push('API documentation updated');
      criteria.push('Error handling implemented');
    }

    return criteria;
  }

  /**
   * Generate test notes
   */
  private static generateTestNotes(requirement: string): TestNotes {
    return {
      testCases: [
        'Happy path scenario',
        'Edge cases handled',
        'Error scenarios covered',
      ],
      testEnvironment: 'Development',
      expectedResults: 'All functionality works as described in requirements',
    };
  }

  /**
   * Estimate hours for a task
   */
  private static estimateHours(text: string): number {
    const lowerText = text.toLowerCase();

    // Complex tasks
    if (lowerText.includes('implement') || lowerText.includes('create') || lowerText.includes('build')) {
      return 8;
    }

    // Medium tasks
    if (lowerText.includes('update') || lowerText.includes('modify')) {
      return 4;
    }

    // Simple tasks
    if (lowerText.includes('fix') || lowerText.includes('change')) {
      return 2;
    }

    return 4; // default
  }

  /**
   * Infer requirements if not explicitly stated
   */
  private static inferRequirements(parsed: any): string[] {
    // If no explicit requirements, break down by common patterns
    const description = parsed.sections.description.join(' ');

    return [
      `Implement core functionality: ${parsed.title}`,
      `Add tests for ${parsed.title}`,
      `Update documentation for ${parsed.title}`,
    ];
  }

  /**
   * Infer technical steps if not explicitly stated
   */
  private static inferTechnicalSteps(): string[] {
    return [
      'Set up project structure and dependencies',
      'Implement core functionality',
      'Add error handling',
      'Write unit tests',
      'Update documentation',
    ];
  }

  /**
   * Clean requirement text
   */
  private static cleanRequirementText(text: string): string {
    return text
      .replace(/^[#-*\d.)\s]+/, '') // Remove markdown and list markers
      .replace(/^(as a|as an|i want|so that)/i, '') // Remove user story prefixes
      .trim()
      .slice(0, 100); // Limit length
  }
}
