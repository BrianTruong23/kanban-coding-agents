'use client';

import { useState } from 'react';
import { FileText, Link as LinkIcon, Image, Loader2, CheckCircle, AlertCircle, Sparkles } from 'lucide-react';
import { breakdownTasksWithAI, BreakdownInput, BreakdownResult, GeneratedTask } from '@/lib/ai/taskBreakdown';
import { Task, TaskType } from '@/types/task';
import { CodingAgent } from '@/types/agent';
import { generateId, generateTaskId } from '@/lib/utils';

interface TaskBreakdownProps {
  onTasksGenerated: (tasks: Task[], dependencies: Array<{ taskId: string; dependsOnTaskId: string }>) => void;
  agents: CodingAgent[];
  existingTasks: Task[];
  onClose: () => void;
}

export const TaskBreakdown = ({ onTasksGenerated, agents, existingTasks, onClose }: TaskBreakdownProps) => {
  const [inputType, setInputType] = useState<'text' | 'file' | 'url' | 'screenshot'>('text');
  const [inputContent, setInputContent] = useState('');
  const [isProcessing, setIsProcessing] = useState(false);
  const [result, setResult] = useState<BreakdownResult | null>(null);
  const [error, setError] = useState<string | null>(null);

  const handleBreakdown = async () => {
    if (!inputContent.trim()) {
      setError('Please provide input content');
      return;
    }

    setIsProcessing(true);
    setError(null);

    try {
      const input: BreakdownInput = {
        type: inputType,
        content: inputContent,
        context: {
          existingTasks,
        },
      };

      const breakdown = await breakdownTasksWithAI(input);
      setResult(breakdown);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Failed to break down tasks');
    } finally {
      setIsProcessing(false);
    }
  };

  const handleGenerateTasks = () => {
    if (!result) return;

    // Calculate the highest task number from existing tasks
    let maxTaskNumber = 0;
    existingTasks.forEach(task => {
      if (task.taskId) {
        const match = task.taskId.match(/TASK-(\d+)/);
        if (match) {
          const num = parseInt(match[1], 10);
          if (num > maxTaskNumber) maxTaskNumber = num;
        }
      }
    });

    // Map temp IDs to real IDs
    const tempIdToRealId = new Map<string, string>();
    let taskCounter = maxTaskNumber + 1;

    // Convert generated tasks to actual tasks
    const allGeneratedTasks = [...result.epics, ...result.stories, ...result.subtasks];
    const tasks: Task[] = allGeneratedTasks.map((genTask) => {
      const realId = generateId();
      tempIdToRealId.set(genTask.tempId, realId);

      return {
        id: realId,
        taskId: generateTaskId(taskCounter++),
        title: genTask.title,
        description: genTask.description,
        status: 'backlog' as const,
        taskType: genTask.taskType,
        parentTaskId: genTask.parentTempId ? undefined : undefined, // Will be set in second pass
        priority: genTask.priority,
        tags: genTask.tags,
        definitionOfDone: genTask.definitionOfDone,
        testNotes: genTask.testNotes,
        riskFlags: genTask.riskFlags,
        estimatedHours: genTask.estimatedHours,
        autoGenerated: true,
        commentsCount: 0,
        attachmentsCount: 0,
        createdAt: Date.now(),
        updatedAt: Date.now(),
      };
    });

    // Second pass: set parent task IDs
    allGeneratedTasks.forEach((genTask, index) => {
      if (genTask.parentTempId) {
        const parentRealId = tempIdToRealId.get(genTask.parentTempId);
        if (parentRealId) {
          tasks[index].parentTaskId = parentRealId;
        }
      }
    });

    // Convert dependencies
    const dependencies = result.dependencies.map(dep => ({
      taskId: tempIdToRealId.get(dep.taskId) || '',
      dependsOnTaskId: tempIdToRealId.get(dep.dependsOnTaskId) || '',
    })).filter(dep => dep.taskId && dep.dependsOnTaskId);

    onTasksGenerated(tasks, dependencies);
    onClose();
  };

  const renderInputSection = () => (
    <div className="space-y-4">
      <div>
        <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
          Input Type
        </label>
        <div className="grid grid-cols-4 gap-2">
          {[
            { type: 'text' as const, icon: FileText, label: 'Text' },
            { type: 'url' as const, icon: LinkIcon, label: 'URL' },
            { type: 'file' as const, icon: FileText, label: 'File' },
            { type: 'screenshot' as const, icon: Image, label: 'Screenshot' },
          ].map(({ type, icon: Icon, label }) => (
            <button
              key={type}
              onClick={() => setInputType(type)}
              className={`p-3 rounded-lg border-2 transition-colors flex flex-col items-center gap-1 ${
                inputType === type
                  ? 'border-black dark:border-white bg-black/5 dark:bg-white/5'
                  : 'border-gray-200 dark:border-gray-600 hover:border-gray-300 dark:hover:border-gray-500'
              }`}
            >
              <Icon size={20} className="text-gray-600 dark:text-gray-400" />
              <span className="text-xs font-medium text-gray-700 dark:text-gray-300">{label}</span>
            </button>
          ))}
        </div>
      </div>

      <div>
        <label className="block text-sm font-medium text-gray-700 dark:text-gray-300 mb-2">
          {inputType === 'text' && 'Paste your PRD, issue, or requirements'}
          {inputType === 'url' && 'Enter URL to PRD or documentation'}
          {inputType === 'file' && 'Upload file (coming soon)'}
          {inputType === 'screenshot' && 'Upload screenshot (coming soon)'}
        </label>
        <textarea
          className="w-full border border-gray-200 dark:border-gray-600 bg-white dark:bg-gray-700 text-gray-900 dark:text-white p-3 rounded-lg h-48 focus:outline-none focus:ring-2 focus:ring-black/10 dark:focus:ring-white/20 resize-none font-mono text-sm"
          placeholder={
            inputType === 'text'
              ? 'Example:\n\nBuild a user authentication system with:\n- Email/password login\n- User registration\n- Password reset\n- Session management\n- Role-based access control'
              : inputType === 'url'
              ? 'https://docs.example.com/prd'
              : 'Upload feature coming soon...'
          }
          value={inputContent}
          onChange={(e) => setInputContent(e.target.value)}
          disabled={inputType === 'file' || inputType === 'screenshot'}
        />
      </div>

      {error && (
        <div className="p-3 bg-red-50 dark:bg-red-900/30 border border-red-200 dark:border-red-800 rounded-lg text-sm text-red-600 dark:text-red-400 flex items-start gap-2">
          <AlertCircle size={16} className="mt-0.5 flex-shrink-0" />
          <span>{error}</span>
        </div>
      )}

      <div className="flex justify-end gap-2">
        <button
          onClick={onClose}
          className="px-4 py-2 text-gray-600 dark:text-gray-400 hover:text-gray-800 dark:hover:text-gray-200 transition-colors"
        >
          Cancel
        </button>
        <button
          onClick={handleBreakdown}
          disabled={isProcessing || !inputContent.trim() || inputType === 'file' || inputType === 'screenshot'}
          className="px-4 py-2 bg-black dark:bg-white text-white dark:text-black rounded-lg hover:bg-gray-800 dark:hover:bg-gray-200 transition-colors font-medium flex items-center gap-2 disabled:opacity-50 disabled:cursor-not-allowed"
        >
          {isProcessing ? (
            <>
              <Loader2 size={16} className="animate-spin" />
              Processing...
            </>
          ) : (
            <>
              <Sparkles size={16} />
              Break Down Tasks
            </>
          )}
        </button>
      </div>
    </div>
  );

  const renderResults = () => {
    if (!result) return null;

    const allTasks = [...result.epics, ...result.stories, ...result.subtasks];
    const taskCount = allTasks.length;

    return (
      <div className="space-y-4">
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-2">
            <CheckCircle size={20} className="text-green-500" />
            <h3 className="text-lg font-bold text-gray-900 dark:text-white">
              Generated {taskCount} Task{taskCount !== 1 ? 's' : ''}
            </h3>
          </div>
          <div className="text-sm text-gray-500 dark:text-gray-400">
            {result.epics.length} Epic{result.epics.length !== 1 ? 's' : ''} • {result.stories.length} Stor
            {result.stories.length !== 1 ? 'ies' : 'y'} • {result.subtasks.length} Subtask
            {result.subtasks.length !== 1 ? 's' : ''}
          </div>
        </div>

        <div className="max-h-96 overflow-y-auto space-y-4 border border-gray-200 dark:border-gray-700 rounded-lg p-4 bg-gray-50 dark:bg-gray-800/50">
          {result.epics.length > 0 && (
            <div>
              <h4 className="text-sm font-bold text-purple-600 dark:text-purple-400 mb-2 uppercase tracking-wide">
                Epics
              </h4>
              {result.epics.map((task) => (
                <TaskPreview key={task.tempId} task={task} />
              ))}
            </div>
          )}

          {result.stories.length > 0 && (
            <div>
              <h4 className="text-sm font-bold text-blue-600 dark:text-blue-400 mb-2 uppercase tracking-wide">
                Stories
              </h4>
              {result.stories.map((task) => (
                <TaskPreview key={task.tempId} task={task} />
              ))}
            </div>
          )}

          {result.subtasks.length > 0 && (
            <div>
              <h4 className="text-sm font-bold text-gray-600 dark:text-gray-400 mb-2 uppercase tracking-wide">
                Subtasks
              </h4>
              {result.subtasks.map((task) => (
                <TaskPreview key={task.tempId} task={task} />
              ))}
            </div>
          )}
        </div>

        {result.dependencies.length > 0 && (
          <div className="p-3 bg-blue-50 dark:bg-blue-900/20 border border-blue-200 dark:border-blue-800 rounded-lg">
            <div className="text-sm font-medium text-blue-900 dark:text-blue-200 mb-1">
              {result.dependencies.length} Dependenc{result.dependencies.length !== 1 ? 'ies' : 'y'} Detected
            </div>
            <div className="text-xs text-blue-700 dark:text-blue-300">
              Tasks will be linked to show blocking relationships
            </div>
          </div>
        )}

        <div className="flex justify-end gap-2 pt-2 border-t border-gray-200 dark:border-gray-700">
          <button
            onClick={() => {
              setResult(null);
              setInputContent('');
            }}
            className="px-4 py-2 text-gray-600 dark:text-gray-400 hover:text-gray-800 dark:hover:text-gray-200 transition-colors"
          >
            Start Over
          </button>
          <button
            onClick={handleGenerateTasks}
            className="px-4 py-2 bg-black dark:bg-white text-white dark:text-black rounded-lg hover:bg-gray-800 dark:hover:bg-gray-200 transition-colors font-medium flex items-center gap-2"
          >
            <CheckCircle size={16} />
            Add All Tasks to Board
          </button>
        </div>
      </div>
    );
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/50 backdrop-blur-sm p-4">
      <div className="bg-white dark:bg-gray-800 p-6 rounded-xl w-full max-w-3xl shadow-xl max-h-[90vh] overflow-y-auto">
        <div className="flex items-center justify-between mb-6">
          <div>
            <h2 className="text-xl font-bold text-gray-900 dark:text-white flex items-center gap-2">
              <Sparkles className="text-purple-500" />
              AI Task Breakdown
            </h2>
            <p className="text-sm text-gray-500 dark:text-gray-400 mt-1">
              Automatically generate epics, stories, and subtasks from your requirements
            </p>
          </div>
        </div>

        {!result ? renderInputSection() : renderResults()}
      </div>
    </div>
  );
};

const TaskPreview = ({ task }: { task: GeneratedTask }) => {
  const typeColors = {
    epic: 'bg-purple-100 dark:bg-purple-900/30 text-purple-700 dark:text-purple-300 border-purple-200 dark:border-purple-800',
    story: 'bg-blue-100 dark:bg-blue-900/30 text-blue-700 dark:text-blue-300 border-blue-200 dark:border-blue-800',
    subtask: 'bg-gray-100 dark:bg-gray-700/30 text-gray-700 dark:text-gray-300 border-gray-200 dark:border-gray-600',
  };

  return (
    <div className={`p-3 rounded-lg border mb-2 ${typeColors[task.taskType]}`}>
      <div className="flex items-start justify-between gap-2">
        <div className="flex-1">
          <div className="font-medium text-sm mb-1">{task.title}</div>
          <div className="text-xs opacity-80 mb-2">{task.description}</div>
          {task.riskFlags.length > 0 && (
            <div className="flex items-center gap-1 text-xs">
              <AlertCircle size={12} className="text-red-500" />
              <span className="text-red-600 dark:text-red-400">
                {task.riskFlags.length} risk flag{task.riskFlags.length !== 1 ? 's' : ''}
              </span>
            </div>
          )}
        </div>
        <div className="flex flex-col items-end gap-1">
          {task.estimatedHours && (
            <div className="text-xs font-mono bg-white/50 dark:bg-black/20 px-2 py-0.5 rounded">
              {task.estimatedHours}h
            </div>
          )}
          {task.priority && (
            <div className="text-xs font-semibold">P{task.priority}</div>
          )}
        </div>
      </div>
    </div>
  );
};
